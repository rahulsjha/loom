"""MkDocs hooks for the documentation site built from docs/.

Each page's meta description is its first sentence, the line llms.txt lists for it, cut to
160 characters, so a search result shows the answer the page opens with. An inline
Markdown link or image that leaves docs/ (source files, the README, llms.txt) points at
the file on GitHub instead of a missing page; links in code blocks and code spans are left
as written, and reference-style links are not rewritten (the docs use inline links). The
sidebar follows llms.txt's section order, with Overview and Quickstart first in Getting
started, and a generated page gets no edit button (its source is the generator, not the
page).

After the build, the site also serves what agents fetch instead of HTML: each page's
Markdown at its source path (`use-cases/agent-memory.md` next to `use-cases/agent-memory/`),
`llms.txt` with its links pointing at those files, `llms-full.txt` with the full text of
the pages that say what Loom is and how to start (the whole docs are several megabytes),
and the repository's `llms-install.md`.
"""

from __future__ import annotations

import html
import posixpath
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from scripts.codegen.page_summary import SECTIONS, page_summary, shorten  # noqa: E402

BLOB = "https://github.com/ClickHouse/loom/blob/main/"
RAW = "https://raw.githubusercontent.com/ClickHouse/loom/main/"
# The generators' whole-page markers; a page with generated regions ("not this region")
# keeps its edit button.
_WHOLLY_GENERATED = re.compile(
    r"<!-- Generated by [^>]*not this page|^This page is generated from", re.MULTILINE
)
# Scanned left to right: a fenced block (indented ones too) or a code span is kept as
# written, an inline link or image may be rewritten. A link's text may hold code spans;
# an image inside a link is matched as the image.
_TOKEN = re.compile(
    r"(?P<fence>^[ \t]*(?P<mark>`{3,}|~{3,})[^\n]*\n.*?^[ \t]*(?P=mark)[ \t]*$)"
    r"|(?P<link>(?P<bang>!?)(?P<text>\[(?:`[^`\n]*`|!(?!\[)|[^\]`!])*\]\()"
    r"(?P<target>[^)\s#]+)(?P<anchor>#[^)\s]*)?(?P<tail>(?:\s+\"[^\"]*\")?\)))"
    r"|(?P<code>``(?:[^`]|`(?!`))+?``|`(?:[^`\n]|\n(?![ \t]*\n))+`)",
    re.DOTALL | re.MULTILINE,
)


_DESCRIPTION_MAX = 160


def on_page_markdown(markdown, page, config, files):
    _title, summary = page_summary(Path(page.file.abs_src_path))
    description = page.meta.get("description") or summary.replace("`", "")
    if description.endswith(":"):
        description = description[:-1] + "."  # an opening sentence that leads into a list
    # Search engines cut a description near this length; end on a whole word instead.
    description = shorten(description, _DESCRIPTION_MAX)
    if description:
        # The theme writes the description into its <meta> attribute unescaped.
        page.meta["description"] = html.escape(description)
    if _WHOLLY_GENERATED.search(markdown):
        page.edit_url = None
    return _rewrite_links(markdown, page.file.src_uri)


def _rewrite_links(markdown: str, src_uri: str, site_url: str = "") -> str:
    """`markdown` of the page at `src_uri` with its links that leave docs/ pointing at GitHub,
    and, given `site_url`, its links inside docs/ pointing at that site's files too."""
    page_dir = posixpath.dirname("docs/" + src_uri)

    def rewrite(m: re.Match[str]) -> str:
        if not m.group("link"):
            return m.group(0)
        target = m.group("target")
        if "://" in target or target.startswith(("mailto:", "/")):
            return m.group(0)
        resolved = posixpath.normpath(posixpath.join(page_dir, target))
        if resolved.startswith("docs/"):
            if not site_url:
                return m.group(0)
            base, resolved = site_url, resolved[len("docs/") :]
        else:
            base = RAW if m.group("bang") else BLOB
        anchor = m.group("anchor") or ""
        return f"{m.group('bang')}{m.group('text')}{base}{resolved}{anchor}{m.group('tail')}"

    return _TOKEN.sub(rewrite, markdown)


_SECTION_RANK = {folder: rank for rank, (_title, folder) in enumerate(SECTIONS)}
_FIRST_PAGES = ("getting-started/overview.md", "getting-started/quickstart.md")


def _folder(section) -> str:
    first = next((c for c in section.children if c.is_page), None)
    return first.file.src_uri.split("/", 1)[0] if first else ""


def _top_key(item) -> tuple[int, str]:
    """The home page, then the sections in llms.txt's order, then loose pages (FAQ, glossary)."""
    if item.is_page:
        uri = item.file.src_uri
        return (-1, uri) if uri == "index.md" else (len(SECTIONS) + 1, uri)
    return (_SECTION_RANK.get(_folder(item), len(SECTIONS)), str(item.title))


def _child_key(item) -> tuple[int, int, str]:
    """Inside a section: its index page, the lead pages, the other pages, then subsections."""
    if not item.is_page:
        return (1, 0, str(item.title))
    uri = item.file.src_uri
    if uri.endswith("/index.md"):
        return (0, 0, uri)
    if uri in _FIRST_PAGES:
        return (0, 1 + _FIRST_PAGES.index(uri), uri)
    return (0, 1 + len(_FIRST_PAGES), uri)


def _pages(items) -> list:
    out = []
    for item in items:
        out.extend(_pages(item.children) if item.is_section else [item])
    return out


def on_nav(nav, config, files):
    nav.items.sort(key=_top_key)
    for item in nav.items:
        if item.is_section:
            item.children.sort(key=_child_key)
    # MkDocs links each page to its neighbours before this event; relink them in the new order.
    nav.pages = _pages(nav.items)
    for i, page in enumerate(nav.pages):
        page.previous_page = nav.pages[i - 1] if i else None
        page.next_page = nav.pages[i + 1] if i + 1 < len(nav.pages) else None
    return nav


# llms-full.txt holds these sections in full, then the pages below; every other page is
# one fetch away through llms.txt.
_FULL_SECTIONS = ("getting-started", "use-cases", "concepts")
_FULL_PAGES = ("faq.md", "glossary.md")
# A docs/ page named in llms.txt, not the tail of a longer path or URL.
_DOCS_PAGE = re.compile(r"(?<![\w/.-])docs/([\w./-]*\.md)")


def _html_url(site_url: str, uri: str) -> str:
    """The HTML page MkDocs builds from the docs/ file at `uri`."""
    page = uri[: -len(".md")]
    if page == "index" or page.endswith("/index"):
        page = page[: -len("index")]
    else:
        page += "/"
    return site_url + page


def _reading_order(docs: Path, folder: str) -> list[Path]:
    """A section's pages in the sidebar's order: its index, the lead pages, then the rest."""
    pages = []
    for p in (docs / folder).rglob("*.md"):
        uri = p.relative_to(docs).as_posix()
        lead = _FIRST_PAGES.index(uri) if uri in _FIRST_PAGES else len(_FIRST_PAGES)
        pages.append((not uri.endswith("/index.md"), lead, uri, p))
    return [p for *_key, p in sorted(pages)]


def on_post_build(config):
    site = Path(config["site_dir"])
    url = config["site_url"]
    docs = ROOT / "docs"
    for src in sorted(docs.rglob("*.md")):
        uri = src.relative_to(docs).as_posix()
        out = site / uri
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(_rewrite_links(src.read_text(encoding="utf-8"), uri), encoding="utf-8")

    # The repository's llms.txt names pages by their docs/ path; on the site each one is
    # its Markdown file, so "docs/use-cases/index.md" becomes "<site>/use-cases/index.md".
    llms = (ROOT / "llms.txt").read_text(encoding="utf-8")
    llms = _DOCS_PAGE.sub(lambda m: url + m.group(1), llms)
    head, sep, rest = llms.partition("\n\n## ")
    full_note = (
        f"The pages that say what Loom is and how to start, in one file: {url}llms-full.txt."
    )
    (site / "llms.txt").write_text(f"{head}\n\n{full_note}{sep}{rest}", encoding="utf-8")

    # The install steps a coding agent follows, at the root as in the repository.
    install = (ROOT / "llms-install.md").read_text(encoding="utf-8")
    (site / "llms-install.md").write_text(
        _rewrite_links(install, "../llms-install.md", url), encoding="utf-8"
    )

    # The title and summary quote of llms.txt open llms-full.txt too.
    intro = head.split("\n\n")[:2]
    parts = [
        "\n\n".join(intro)
        + f"\n\nThis file holds some sections in full; {url}llms.txt lists every page.\n"
    ]
    pages = [p for folder in _FULL_SECTIONS for p in _reading_order(docs, folder)]
    for src in pages + [docs / name for name in _FULL_PAGES]:
        uri = src.relative_to(docs).as_posix()
        # One file holds every page, so a link between them names the page's own file.
        body = _rewrite_links(src.read_text(encoding="utf-8"), uri, url)
        source = f"Source: {_html_url(url, uri)} (Markdown: {url}{uri})"
        parts.append(f"{source}\n\n{body.strip()}\n")
    (site / "llms-full.txt").write_text("\n---\n\n".join(parts), encoding="utf-8")
